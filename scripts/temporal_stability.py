"""Summarize the month-by-month stability runs.

Usage:
    python scripts/temporal_stability.py

Reads `reports/temporal/m5/pilot.json` and `reports/temporal/m6/pilot.json`,
writes `reports/temporal_stability.json` and `.md`.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    "month_5": ROOT / "reports" / "temporal" / "m5" / "pilot.json",
    "month_6": ROOT / "reports" / "temporal" / "m6" / "pilot.json",
}


def _load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _summary(payload: dict, estimator: str) -> list[dict]:
    return [
        r
        for r in payload["summary"]
        if r["scenario"] == "main" and r["estimator"] == estimator
    ]


def _ranking(payload: dict, estimator: str) -> dict:
    rows = [
        r
        for r in payload.get("ranking", [])
        if r["scenario"] == "main" and r["estimator"] == estimator
    ]
    return rows[0] if rows else {}


def summarize(payload: dict) -> dict:
    naive = _summary(payload, "naive")
    dr = _summary(payload, "dr")
    ipw = _summary(payload, "ipw_ht")
    return {
        "months": payload["data"]["months"],
        "n": payload["data"]["n"],
        "fraud_rate": payload["data"]["fraud_rate"],
        "naive_max_abs_rel_bias": max(abs(r["rel_bias"]) for r in naive),
        "dr_max_abs_rel_bias": max(abs(r["rel_bias"]) for r in dr),
        "dr_mean_coverage": sum(r["coverage"] for r in dr) / len(dr),
        "ipw_max_abs_rel_bias": max(abs(r["rel_bias"]) for r in ipw),
        "naive_p_best": _ranking(payload, "naive").get("p_select_true_best"),
        "dr_p_best": _ranking(payload, "dr").get("p_select_true_best"),
        "naive_inversions": _ranking(payload, "naive").get("mean_inversions"),
        "dr_inversions": _ranking(payload, "dr").get("mean_inversions"),
    }


def main() -> None:
    out = {}
    for name, path in SOURCES.items():
        if not path.exists():
            raise SystemExit(f"missing {path}; run the month pilots first")
        out[name] = summarize(_load(path))
    payload = {
        "note": "Month-by-month stability of the main scenario; 100 reps each.",
        "results": out,
    }
    (ROOT / "reports" / "temporal_stability.json").write_text(
        json.dumps(payload, indent=2), encoding="utf-8"
    )

    lines = [
        "# Temporal Stability",
        "",
        "_Generated by `scripts/temporal_stability.py` from the month pilots._",
        "",
        "| Month | n | Fraud rate | Naive max bias | DR max bias | DR coverage | Naive P(best) | DR P(best) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, r in out.items():
        lines.append(
            f"| {name} | {r['n']:,} | {r['fraud_rate']:.4%} | "
            f"{r['naive_max_abs_rel_bias']:.2%} | "
            f"{r['dr_max_abs_rel_bias']:.2%} | "
            f"{r['dr_mean_coverage']:.1%} | "
            f"{r['naive_p_best']:.0%} | {r['dr_p_best']:.0%} |"
        )
    lines.append("")
    lines.append(
        "Both months use the same observation mechanism, cost matrix, and 100 "
        "replications; only the evaluation month changes. The check asks whether "
        "the sign of the bias and the ranking conclusion survive."
    )
    (ROOT / "reports" / "temporal_stability.md").write_text(
        "\n".join(lines), encoding="utf-8"
    )
    print("\n".join(lines))


if __name__ == "__main__":
    main()
