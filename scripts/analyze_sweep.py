"""Summarize an observation-rate sweep from a pilot JSON payload.

Usage:
    python scripts/analyze_sweep.py \
        --json reports/obs_sweep/pilot.json \
        --out reports/obs_sweep
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd


def _max_abs(series: pd.Series) -> float:
    values = pd.to_numeric(series, errors="coerce").to_numpy(dtype=float)
    values = values[np.isfinite(values)]
    return float(np.abs(values).max()) if len(values) else float("nan")


def _mean(series: pd.Series) -> float:
    values = pd.to_numeric(series, errors="coerce").to_numpy(dtype=float)
    values = values[np.isfinite(values)]
    return float(values.mean()) if len(values) else float("nan")


def summarize(payload: dict) -> pd.DataFrame:
    summary = pd.DataFrame(payload["summary"])
    ranking = pd.DataFrame(payload.get("ranking", []))
    rows = []
    for scenario in sorted(summary["scenario"].unique()):
        part = summary[summary["scenario"] == scenario]
        rank = (
            ranking[ranking["scenario"] == scenario] if not ranking.empty else ranking
        )

        def max_bias(estimator: str) -> float:
            return _max_abs(part.loc[part["estimator"] == estimator, "rel_bias"])

        def mean_cov(estimator: str) -> float:
            return _mean(part.loc[part["estimator"] == estimator, "coverage"])

        def rank_metric(estimator: str, column: str) -> float:
            if rank.empty:
                return float("nan")
            return _mean(rank.loc[rank["estimator"] == estimator, column])

        rows.append(
            {
                "scenario": scenario,
                "naive_max_bias": max_bias("naive"),
                "dr_max_bias": max_bias("dr"),
                "ipw_max_bias": max_bias("ipw_ht"),
                "audit_max_bias": max_bias("audit_only"),
                "dr_mean_coverage": mean_cov("dr"),
                "naive_inversions": rank_metric("naive", "mean_inversions"),
                "dr_inversions": rank_metric("dr", "mean_inversions"),
                "naive_p_best": rank_metric("naive", "p_select_true_best"),
                "dr_p_best": rank_metric("dr", "p_select_true_best"),
            }
        )
    return pd.DataFrame(rows)


def _pct(value: float) -> str:
    return "n/a" if not np.isfinite(value) else f"{value:.2%}"


def _num(value: float, digits: int = 2) -> str:
    return "n/a" if not np.isfinite(value) else f"{value:.{digits}f}"


def main() -> None:
    parser = argparse.ArgumentParser(description="Summarize an observation sweep.")
    parser.add_argument("--json", default="reports/obs_sweep/pilot.json", type=Path)
    parser.add_argument("--out", default="reports/obs_sweep", type=Path)
    args = parser.parse_args()

    payload = json.loads(args.json.read_text(encoding="utf-8"))
    table = summarize(payload)
    args.out.mkdir(parents=True, exist_ok=True)
    table.to_csv(args.out / "obs_sweep_summary.csv", index=False)

    lines = [
        "# Observation-Rate Sweep",
        "",
        "_Generated by `scripts/analyze_sweep.py` from the pilot JSON._",
        "",
        "| Scenario | Naive max bias | DR max bias | IPW max bias | DR coverage | Naive inversions | DR inversions | DR P(best) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for _, row in table.iterrows():
        lines.append(
            f"| `{row['scenario']}` | {_pct(row['naive_max_bias'])} | "
            f"{_pct(row['dr_max_bias'])} | {_pct(row['ipw_max_bias'])} | "
            f"{_pct(row['dr_mean_coverage'])} | {_num(row['naive_inversions'])} | "
            f"{_num(row['dr_inversions'])} | {_pct(row['dr_p_best'])} |"
        )
    lines.append("")
    (args.out / "obs_sweep.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.out / 'obs_sweep.md'}")
    print(f"wrote {args.out / 'obs_sweep_summary.csv'}")


if __name__ == "__main__":
    main()
